package com.java.oops;

public class Vehicle {
	private double vechicleNumber;
	private String vechicleType;
	private String ownerName;
	public double getVechicleNumber() {
		return vechicleNumber;
	}
	public void setVechicleNumber(double vechicleNumber) {
		this.vechicleNumber = vechicleNumber;
	}
	public String getVechicleType() {
		return vechicleType;
	}
	public void setVechicleType(String vechicleType) {
		this.vechicleType = vechicleType;
	}
	public String getOwnerName() {
		return ownerName;
	}
	public void setOwnerName(String ownerName) {
		this.ownerName = ownerName;
	}

}
